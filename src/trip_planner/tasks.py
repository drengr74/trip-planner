"""Три поручения. Текст поездки подставляется при вызове, не при импорте."""

from dataclasses import dataclass

from crewai import Task

from .agents import TripAgents
from .geocode import GeocodeResult
from .maps_tools import OSRM_TIME_LABEL, format_intercity_driving
from .places_osm import OSM_INTEREST_NOT_FOUND
from .trip import TripRequest, format_trip


@dataclass(frozen=True)
class TripTasks:
    research: Task
    itinerary: Task
    review: Task


def create_tasks(
    trip: TripRequest,
    agents: TripAgents,
    destination: GeocodeResult,
) -> TripTasks:
    """Собирает задачи для уже проверенной поездки, ролей и центра назначения."""
    conditions = _plain(format_trip(trip))
    center = _plain(_center_context(trip, destination))
    # Координат отправления в поездке нет — OSRM между городами не вызывается.
    intercity = _plain(
        format_intercity_driving(
            trip.origin,
            trip.destination,
            destination_latitude=destination.latitude,
            destination_longitude=destination.longitude,
        )
    )

    research = Task(
        description=(
            "Собери идеи под интересы путешественника по условиям ниже.\n"
            f"{conditions}\n"
            f"{center}\n"
            "Обязательно вызови инструмент поиска достопримечательностей Overpass. "
            "В итоговый список включай только места из ответа инструмента: "
            "название дословно как в строке инструмента, OSM ID (тип/номер) "
            "и расстояние до центра. "
            "Не переводи название и не заменяй его другим написанием. "
            "Тип места бери готовым из той же строки. "
            "Координаты каждой точки вынеси отдельной строкой и скопируй "
            "её целиком из инструмента. На этой строке только широта и долгота "
            "через запятую и пробел: без подписи, скобок, знака градуса "
            "и сторон света. "
            "Не добавляй места, которых нет в ответе Overpass. "
            "Для каждого места укажи метку географии: «в городе» или "
            "«поездка в окрестности» по расстоянию до центра. "
            "Цены и наличие мест не подтверждай. "
            "Время в пути на этом шаге не оценивай — это сделает планировщик. "
            "Перечисли каждый интерес из условий. Для интереса укажи места "
            "из ответа инструмента, которые ему подходят. Если подходящего "
            f"объекта в данных OSM нет, напиши ровно «{OSM_INTEREST_NOT_FOUND}». "
            "Не выдумывай место, зал или клуб вместо этой фразы."
        ),
        expected_output=(
            "Список только найденных через Overpass мест: название, OSM ID, "
            "отдельная строка координат для Google Maps, расстояние до центра, "
            "категория, метка географии, "
            "почему подходит интересам. По каждому интересу — либо такие места, "
            f"либо фраза «{OSM_INTEREST_NOT_FOUND}». "
            "Отдельно — что не проверено (цены и т.п.)."
        ),
        agent=agents.researcher,
    )
    itinerary = Task(
        description=(
            "Составь маршрут по дням по результатам исследования и условиям ниже.\n"
            f"{conditions}\n"
            f"{center}\n"
            "В обычные точки дня включай только места из списка исследователя "
            "с тем же названием и OSM ID. Название не переписывай. "
            "Координаты каждой точки — отдельной строкой, дословно как "
            "в исследовании: только широта, долгота, без подписи, скобок, "
            "знака градуса и сторон света. "
            "Новые достопримечательности не выдумывай. "
            f"{intercity}\n"
            "Для каждой точки за городом (или когда нужно время от центра) вызови "
            "инструмент OSRM driving от центра назначения до координат места. "
            f"Любое полученное время явно помечай как «{OSRM_TIME_LABEL}» "
            "и учти дорогу туда и обратно в плане дня. "
            "Если OSRM недоступен или маршрута нет — напиши «сверить по карте» "
            "и не делай день вокруг этой точки плотным. "
            "Общественный транспорт не выдумывай. "
            "Способ междугородней дороги — тот, что указал пользователь. "
            "Его длительность не оценивай по прямой: только готовая строка участка выше."
        ),
        expected_output=(
            "Маршрут по дням (утро, день, вечер) и шаг междугородней дороги "
            "с готовой формулировкой времени. "
            "У каждой включённой точки — то же название, OSM ID и та же "
            "отдельная строка координат, что в исследовании. "
            f"Для загородных (и где считалось время) — длительность в одну сторону "
            f"с пометкой «{OSRM_TIME_LABEL}» либо «сверить по карте», "
            "и учтён туда-обратно. Места вне списка исследователя не включены."
        ),
        agent=agents.planner,
        context=[research],
    )
    review = Task(
        description=(
            "Проверь маршрут по условиям бюджета и качеству.\n"
            f"{conditions}\n"
            f"{center}\n"
            "Считай внутри бюджета только категории, которые пользователь включил. "
            "Если цены не подтверждены, прямо напиши, что достаточность бюджета "
            "подтвердить нельзя. "
            "Отметь точки без OSM ID/координат из исследования и загородные точки "
            f"без времени с пометкой «{OSRM_TIME_LABEL}» или «сверить по карте». "
            "Не отклоняй место только потому, что оно за городом, "
            "если оно найдено через OSM. "
            "По каждому интересу проверь исследование: либо есть объект "
            "из OpenStreetMap, либо ровно фраза "
            f"«{OSM_INTEREST_NOT_FOUND}». Место, которого нет в данных OSM, "
            "считай ошибкой."
        ),
        expected_output=(
            "Замечания по темпу, интересам, географии и бюджету. "
            "По каждому интересу — объект OSM или фраза "
            f"«{OSM_INTEREST_NOT_FOUND}». "
            "Список проблемных точек (нет OSM-данных, выдуманное место "
            "или нет корректной пометки времени). Оценки трат «не подтверждено». "
            "Фраза о том, что достаточность бюджета подтвердить нельзя, "
            "если цены не проверены."
        ),
        agent=agents.reviewer,
        context=[research, itinerary],
    )
    return TripTasks(research=research, itinerary=itinerary, review=review)


def _center_context(trip: TripRequest, destination: GeocodeResult) -> str:
    """Имя назначения совпадает с «Куда» в условиях; регион — только контекст."""
    place = trip.destination
    context = [
        part
        for part in (destination.region.strip(), destination.country.strip())
        if part and part.casefold() not in place.casefold()
    ]
    line = f"Населённый пункт назначения: {place}."
    if context:
        line += " Контекст: " + ", ".join(context) + "."
    line += (
        f" Координаты центра: {destination.latitude:.5f}, "
        f"{destination.longitude:.5f}."
    )
    return line


def _plain(text: str) -> str:
    """Убирает фигурные скобки, чтобы текст поездки не стал шаблоном CrewAI."""
    return text.replace("{", "(").replace("}", ")")
