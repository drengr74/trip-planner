"""Три поручения. Текст поездки подставляется при вызове, не при импорте."""

from dataclasses import dataclass

from crewai import Task

from .agents import TripAgents
from .geocode import GeocodeResult
from .maps_tools import (
    INTEREST_MATCH_TITLE,
    OSRM_TIME_LABEL,
    ROUTE_CHECK_TITLE,
    format_intercity_driving,
)
from .trip import TripRequest, format_trip
from .web_search import (
    OSM_INTEREST_CONFIRMED,
    OSM_INTEREST_UNCONFIRMED,
    WEB_BLOCK_TITLE,
    WEB_NOT_ON_TOPIC,
)


@dataclass(frozen=True)
class TripTasks:
    research: Task
    itinerary: Task
    review: Task


def create_tasks(
    trip: TripRequest,
    agents: TripAgents,
    destination: GeocodeResult,
    origin: GeocodeResult | None = None,
) -> TripTasks:
    """Собирает задачи для уже проверенной поездки, ролей и центра назначения.

    Координаты отправления попадают в межгородской OSRM только если населённый
    пункт выбран явно. Иначе минуты, километры и номера дорог не подставляются.
    """
    conditions = _plain(format_trip(trip))
    center = _plain(_center_context(trip, destination))
    origin_line = _plain(_origin_context(origin))
    intercity = _plain(
        format_intercity_driving(
            trip.origin,
            trip.destination,
            origin_latitude=None if origin is None else origin.latitude,
            origin_longitude=None if origin is None else origin.longitude,
            destination_latitude=destination.latitude,
            destination_longitude=destination.longitude,
        )
    )
    agents.web_state["intercity"] = intercity

    research = Task(
        description=(
            "Собери идеи под интересы путешественника по условиям ниже.\n"
            f"{conditions}\n"
            f"{center}\n"
            "Обязательно вызови инструмент поиска достопримечательностей Overpass. "
            "В итоговый список включай только места из ответа инструмента: "
            "название дословно как в строке инструмента, OSM ID (тип/номер) "
            "и расстояние до центра. "
            "Не переводи название и не заменяй его другим написанием. "
            "Тип места бери готовым из той же строки. "
            "Координаты каждой точки вынеси отдельной строкой и скопируй "
            "её целиком из инструмента: пять знаков после запятой, "
            "«широта, долгота», без другого текста на этой строке. "
            "Не добавляй места, которых нет в ответе Overpass. "
            "Для каждого места укажи метку географии: «в городе» или "
            "«поездка в окрестности» по расстоянию до центра. "
            "Цены и наличие мест не подтверждай. "
            "Время в пути на этом шаге не оценивай — это сделает планировщик. "
            f"Блок «{INTEREST_MATCH_TITLE}» скопируй дословно: это единственный "
            "список подходящих мест. Не решай соответствие сам и не добавляй "
            "объект к интересу, если его нет в этом блоке. "
            "Fire & Boxing Demonstration и Stage не подтверждают BJJ, "
            "если блок их туда не поставил. "
            f"Если статус — «{OSM_INTEREST_CONFIRMED}», перечисли только "
            "объекты из блока и не пиши, что OSM интерес не подтвердил. "
            f"Если статус — «{OSM_INTEREST_UNCONFIRMED}», скопируй эту фразу. "
            "Кандидаты Tavily ещё не источники. Для каждого такого интереса "
            "оставь адрес только когда по заголовку, URL и фрагменту ясно оба "
            "условия: содержание относится к этому интересу, и оно относится "
            "к выбранному населённому пункту или его региону. "
            "Учитывай синонимы, сокращения, переводы и другие формулировки. "
            "Отдельного правила для одного вида интереса нет. "
            "Город при другой теме не оставляй. Неясную связь не оставляй. "
            "Подходящие адреса скопируй дословно одной строкой вида "
            "Оставить URL по интересу «название»: адрес. "
            "Если не осталось ни одного, напиши эту строку без адресов. "
            "Заголовок и фрагмент не переписывай: их подставит программа "
            "из исходного ответа Tavily. Новый адрес не добавляй и страницу не открывай. "
            "Не называй те же объекты подходящими в другом разделе. "
            "Не пиши, что объекта нет в OSM: этот запрос не покрывает все типы. "
            "Веб-источник не делай местом OSM: без OSM ID и без координат. "
            "Не заменяй веб-блок общими советами и не придумывай места, "
            "клубы, сайты или URL. "
            f"Фраза «{WEB_NOT_ON_TOPIC}» — не сбой сервиса: "
            "отброшенные ссылки не восстанавливай. "
            "Цену, расписание и наличие места из веб-фрагмента приводи только "
            "вместе с URL и пометкой, что их нужно проверить."
        ),
        expected_output=(
            "Список только найденных через Overpass мест: название, OSM ID, "
            "отдельная строка координат для Google Maps, расстояние до центра, "
            "категория, метка географии. По каждому интересу — тот же статус, "
            f"что в блоке «{INTEREST_MATCH_TITLE}»: либо «{OSM_INTEREST_CONFIRMED}» "
            "и те же OSM ID, либо "
            f"«{OSM_INTEREST_UNCONFIRMED}» и веб-блок без координат. "
            "Отдельно — что не проверено (цены и т.п.)."
        ),
        agent=agents.researcher,
    )
    itinerary = Task(
        description=(
            "Составь маршрут по дням по результатам исследования и условиям ниже.\n"
            f"{conditions}\n"
            f"{center}\n"
            "В обычные точки дня включай только места из списка исследователя "
            "с тем же названием и OSM ID. Название не переписывай. "
            f"К интересу относи только объекты из блока «{INTEREST_MATCH_TITLE}» "
            "с этим интересом. "
            "Координаты каждой точки — ровно одна строка, которую можно целиком "
            "скопировать в Google Maps: пять знаков после запятой, "
            "формат «широта, долгота», без подписи и другого текста на этой строке. "
            f"{_day_count_rule(trip.days)} "
            "Новые достопримечательности не выдумывай. "
            f"Строки из блока «{WEB_BLOCK_TITLE}» не включай как точки маршрута "
            "и не назначай им координаты. "
            f"{origin_line}\n"
            f"{intercity}\n"
            "Для каждой точки за городом (или когда нужно время от центра) вызови "
            "инструмент OSRM driving от центра назначения до координат места. "
            "Этот вызов не даёт названий и номеров дорог. "
            "Ответ инструмента даёт расчётное время и расстояние отдельными строками. "
            "Копируй обе, если обе есть. Если есть только одна, копируй её "
            "и не подставляй вторую. Километры не называй временем. "
            f"Пометка значений — «{OSRM_TIME_LABEL}». "
            "Не пиши, что время или маршрут подтверждены. "
            "Оценка в одну сторону; дорогу обратно учитывай отдельно "
            "и тоже как расчётную оценку. "
            "Если OSRM недоступен или маршрута нет — напиши «сверить по карте» "
            "и не делай день вокруг этой точки плотным. "
            "Общественный транспорт не выдумывай. "
            "Способ междугородней дороги — тот, что указал пользователь. "
            "Его длительность не оценивай по прямой: только готовая строка участка выше. "
            "Названия и номера дорог копируй только из этой строки межгородского участка. "
            "ref копируй дословно: не меняй написание и не называй дорогу главной трассой, "
            "если этих слов нет в строке шагов. "
            "Для переездов между точками дня названия и номера дорог не указывай."
        ),
        expected_output=(
            f"Маршрут на {trip.days} дн.: у каждого дня заголовок, "
            "либо точки, либо фраза «для этого дня подходящих точек не найдено». "
            "Шаг междугородней дороги с отдельными строками расчётного времени "
            "и расстояния, если они есть, и с названиями и номерами дорог "
            "только из строки участка. "
            "У каждой включённой точки — то же название, OSM ID и одна строка "
            "«широта, долгота» с пятью знаками после запятой. "
            f"Для участка до точки — строки инструмента с пометкой «{OSRM_TIME_LABEL}» "
            "либо «сверить по карте». Время и маршрут не названы подтверждёнными. "
            "Места вне списка исследователя не включены."
        ),
        agent=agents.planner,
        context=[research],
    )
    review = Task(
        description=(
            "Проверь маршрут по условиям бюджета и качеству.\n"
            f"{conditions}\n"
            f"{center}\n"
            f"{origin_line}\n"
            f"{intercity}\n"
            "Пустые дни, повторы OSM ID и наличие ID у точек считает программа. "
            f"Не устанавливай эти факты сам и не противоречь блоку "
            f"«{ROUTE_CHECK_TITLE}». "
            "Если в нём сказано, что пустых дней нет, не пиши, что день пустой. "
            "Если у места в списке исследователя есть OSM ID, не пиши, что ID нет. "
            "Если ID встретился в маршруте один раз, не называй место повтором. "
            "Неизвестный ID обозначай как неизвестный, не как отсутствующий. "
            "Координаты точки должны быть одной строкой «широта, долгота» "
            "с пятью знаками после запятой. "
            "Километры, названные временем, и фраза, что время или маршрут OSRM "
            "подтверждены, — ошибка: это расчётная оценка. "
            "Сверь названия и номера дорог в маршруте со списком расчётных шагов OSRM "
            "в готовой строке межгородского участка. Название, номер или слова "
            "«главная трасса», которых нет в этом списке, отметь как неподтверждённые. "
            "Этот список не подтверждает пробки, ремонты и дорожную безопасность: "
            "не пиши, что дорога свободна, открыта или безопасна. "
            "Если в строке участка есть «время не проверено, сверьте по карте», "
            "минуты, километры и номера дорог между городами в маршруте — ошибка. "
            "Номера и названия дорог у переездов между точками дня, "
            "которых нет в межгородском списке, тоже неподтверждены. "
            "Считай внутри бюджета только категории, которые пользователь включил. "
            "Бюджет и отсутствие цен в замечания не переноси: это отдельный раздел. "
            "Не повторяй успешные проверки: пустые дни, наличие ID и отсутствие повторов "
            "уже считает программа и в текст плана не выводит. "
            "Загородная точка с OSM ID из исследования допустима. Отметь её только "
            "если для участка нет строки расчётного времени или расстояния "
            f"с пометкой «{OSRM_TIME_LABEL}» и нет фразы «сверить по карте». "
            f"Интересы сверяй только с блоком «{INTEREST_MATCH_TITLE}» из исследования. "
            "Не копируй этот блок и не решай соответствие заново. "
            "Объект, которого нет под интересом в этом блоке, не называй подходящим. "
            f"Статус «{OSM_INTEREST_CONFIRMED}» и «{OSM_INTEREST_UNCONFIRMED}» "
            "нельзя противоречить друг другу для одного интереса. "
            f"Фраза «{OSM_INTEREST_UNCONFIRMED}» не значит, что объекта нет в OSM. "
            "Веб-ссылка не даёт OSM-подтверждения. "
            f"Блок «{WEB_BLOCK_TITLE}» — источник описания, не объект OSM. "
            "Не придумывай достопримечательности, чтобы заполнить день. "
            "URL без OSM ID не делает веб-источник ненадёжным и не значит, "
            "что сайт не найден в OSM. Не отбирай веб-источники заново и не "
            "добавляй адрес, которого нет в уже отобранном блоке. "
            "Ошибка — использовать такую строку как точку маршрута, дать ей координаты "
            "или адрес, либо добавить точку, дорогу или цену, которых нет во входе. "
            "Замечание пиши только по конкретной строке входа. "
            "Не оценивай тон отзывов и не давай общих советов без этой строки."
        ),
        expected_output=(
            "Замечания только по конкретным строкам входа: темп, интересы, "
            "география и бюджет. "
            "По каждому интересу — тот же статус, "
            f"что в блоке «{INTEREST_MATCH_TITLE}», без повторной вставки блока. "
            "Веб-источник с URL не назван отсутствующим в OSM. "
            "Проблема — только точка маршрута из веб-блока, дорога вне шагов OSRM "
            "или цена без URL и пометки о проверке. "
            "Оценки трат «не подтверждено». "
            "Фраза о том, что достаточность бюджета подтвердить нельзя, "
            "если цены не проверены."
        ),
        agent=agents.reviewer,
        context=[research, itinerary],
    )
    return TripTasks(research=research, itinerary=itinerary, review=review)


def _day_count_rule(days: int) -> str:
    """Маршрут держит число дней из параметров поездки."""
    return (
        f"Длительность поездки — {days} дн. "
        f"В маршруте должны быть все дни от 1 до {days}. "
        "Если для дня не осталось подходящих точек из исследования, "
        "оставь заголовок этого дня и напиши: "
        "«для этого дня подходящих точек не найдено». "
        "Если в дне уже есть точка с OSM ID из списка исследователя, "
        "эту фразу не добавляй. Дорожные шаги переезда между городами "
        "точками дня не считаются. "
        "Не сокращай число дней и не выдумывай точки, чтобы заполнить день."
    )


def _origin_context(origin: GeocodeResult | None) -> str:
    """Координаты выбранного отправления. Без выбора OSRM между городами не звать."""
    if origin is None:
        return (
            "Населённый пункт отправления не выбран. "
            "Координаты отправления в межгородской маршрут не переданы."
        )
    place = origin.place_name.strip() or origin.display_name.split(",")[0].strip()
    return (
        f"Населённый пункт отправления: {place}. "
        f"Координаты центра отправления: {origin.latitude:.5f}, "
        f"{origin.longitude:.5f}."
    )


def _center_context(trip: TripRequest, destination: GeocodeResult) -> str:
    """Имя назначения совпадает с «Куда» в условиях; регион — только контекст."""
    place = trip.destination
    context = [
        part
        for part in (destination.region.strip(), destination.country.strip())
        if part and part.casefold() not in place.casefold()
    ]
    line = f"Населённый пункт назначения: {place}."
    if context:
        line += " Контекст: " + ", ".join(context) + "."
    line += (
        f" Координаты центра: {destination.latitude:.5f}, "
        f"{destination.longitude:.5f}."
    )
    return line


def _plain(text: str) -> str:
    """Убирает фигурные скобки, чтобы текст поездки не стал шаблоном CrewAI."""
    return text.replace("{", "(").replace("}", ")")
