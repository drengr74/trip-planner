"""Три роли планировщика поездки. Модель и OSM-инструменты передаются снаружи."""

from dataclasses import dataclass

from crewai import Agent, LLM
from crewai.tools import BaseTool

from .geocode import GeocodeResult
from .maps_tools import build_planner_tools, build_researcher_tools


@dataclass(frozen=True)
class TripAgents:
    researcher: Agent
    planner: Agent
    reviewer: Agent
    web_state: dict[str, object]


def create_agents(
    llm: LLM,
    destination: GeocodeResult,
    interests: tuple[str, ...] = (),
) -> TripAgents:
    """Один LLM на всех; исследователю — Overpass, планировщику — OSRM driving."""
    web_state: dict[str, object] = {"blocked": False, "cache": {}}
    researcher_tools: list[BaseTool] = build_researcher_tools(
        destination, interests, web_state
    )
    planner_tools: list[BaseTool] = build_planner_tools(destination)
    researcher = Agent(
        role="Исследователь направления и идей",
        goal=(
            "С помощью инструмента Overpass собрать только реально найденные места "
            "около центра города назначения. Название и тип копировать дословно "
            "из ответа инструмента. Для каждого места указать OSM ID, "
            "координаты, расстояние до центра и метку географии. "
            "Цены и наличие мест помечать как непроверенные. "
            "Блок соответствия интересов копировать дословно и не решать самому, "
            "подходит ли место. Из кандидатов Tavily оставлять URL только когда "
            "по заголовку, URL и фрагменту ясны и интерес, и выбранный пункт или "
            "его регион, включая синонимы, сокращения и переводы. "
            "Адрес копировать дословно в строку «Оставить URL». "
            "Заголовки, фрагменты и новые адреса не придумывать."
        ),
        backstory=(
            "Ты готовишь черновик идей для поездки одного человека. "
            "Места с координатами берёшь только из ответа Overpass. "
            "Веб-источник остаётся ссылкой: без OSM ID и без координат. "
            "Связь кандидата с темой и местом оцениваешь по уже полученным "
            "заголовку, URL и фрагменту, в том же ответе, без нового поиска. "
            "Ты не составляешь расписание по дням и не подтверждаешь бюджет."
        ),
        llm=llm,
        tools=researcher_tools,
        allow_delegation=False,
    )
    planner = Agent(
        role="Планировщик маршрута",
        goal=(
            "Собрать маршрут по дням только из мест, которые нашёл исследователь, "
            "с теми же названиями, OSM ID и координатами. Время до точки считать "
            "инструментом OSRM driving от центра назначения. Время и расстояние "
            "писать отдельно и помечать как расчётную оценку на авто по OSRM, "
            "не как подтверждённые. Время между городами не оценивать по прямой. "
            "Названия и номера дорог брать только из готовой строки "
            "межгородского участка."
        ),
        backstory=(
            "Ты раскладываешь найденные OSM-места по дням. "
            "Новые места без данных исследователя не добавляешь. "
            "Веб-находку не ставишь точкой маршрута и не даёшь ей координаты. "
            "Время в пути не выдумываешь: только OSRM driving или «сверить по карте». "
            "Номера дорог между точками дня не придумываешь: их нет в расчёте "
            "от центра назначения до точки."
        ),
        llm=llm,
        tools=planner_tools,
        allow_delegation=False,
    )
    reviewer = Agent(
        role="Проверяющий бюджет и качество",
        goal=(
            "Проверить маршрут по бюджету, темпу и тому, что в плане только "
            "места с OSM ID из исследования, а время и расстояние помечены как "
            "расчётная оценка на авто по OSRM или «сверить по карте». "
            "Если цены не подтверждены, написать, что достаточность бюджета "
            "подтвердить нельзя. "
            "Дорожное название или номер, которого нет в расчётных шагах "
            "межгородского OSRM, отметить как неподтверждённые. "
            "Подходящие места брать только из общего блока соответствия интересов "
            "и этот блок не переписывать. "
            "Веб-источник с URL не смешивать с точкой OSM. "
            "Пустоту дней, повторы и наличие OSM ID не устанавливать: "
            "это делает программа."
        ),
        backstory=(
            "Ты сверяешь план с правилом бюджета путешественника и только с теми "
            "строками, которые уже есть во входе. "
            "Поездка в окрестности допустима, если место найдено через OSM. "
            "Оценки цен не называешь фактами. "
            "Не решаешь, пустой ли день, повтор ли место и есть ли у него OSM ID. "
            "Подходит ли место интересу, берёшь только из блока соответствия, "
            "а не из веб-ссылки и не из смежной категории. "
            "Веб-блок с URL и без OSM ID — источник описания. "
            "Его состав уже отобран, заново релевантность не решаешь и адреса не добавляешь. "
            "Новые достопримечательности для пустого дня не придумываешь. "
            "Не пишешь, что сайт не найден в OSM, и не оцениваешь тон отзывов. "
            "Точку маршрута, адрес, дорогу или цену из этого блока считаешь ошибкой. "
            "Дорогу вне расчётных шагов OSRM считаешь неподтверждённой. "
            "Общий совет без строки источника не добавляешь."
        ),
        llm=llm,
        tools=[],
        allow_delegation=False,
    )
    return TripAgents(
        researcher=researcher,
        planner=planner,
        reviewer=reviewer,
        web_state=web_state,
    )
